from numpy import*

"""integer"""
a = array([1,2,3,4,5,6,7])
print(a)

a = array([1,2,3,4,5,6,7],int)
print(a)

"""FLOAT"""

a = array([1.1,1.4,2.0,4.5,6.6])
print(a)

a = array([1.1,1.4,2.0,4.5,6.6],float)
print(a)

"""CHAR"""

a =array(['a','b','c','d','e'])
print(a)

a =array(['a','b','c','d','e'],dtype=str)
print(a)

